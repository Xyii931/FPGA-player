    input wire I_video_abort,
    output wire O_active_valid,
    output wire [15:0] O_active_tag,
    output wire [31:0] O_active_epoch,
    output wire O_applied_pulse,
    output wire O_apply_valid,
    output wire O_retire_valid,
    input wire I_retire_ready,
    output wire [15:0] O_retire_tag,
    output wire [31:0] O_retire_epoch,
    output wire O_retire_old,
    input wire I_retire_done_valid,
    output wire O_retire_done_ready,
    input wire [15:0] I_retire_done_tag,
    input wire [31:0] I_retire_done_epoch,
    input wire [3:0] I_retire_done_error,
    output wire O_video_quarantined,
    output wire O_video_response_discarded,
    input wire [1:0] I_source_mask,
    output wire [1:0] O_pending_source_mask,
    output wire [1:0] O_active_source_mask,
    output wire [1:0] O_retire_source_mask,
    input wire I_from_source,
    output wire O_pending_from_source,
    output wire O_active_from_source,
    output wire O_retire_from_source,
    input wire [5:0] I_slots,
    output wire [5:0] O_pending_slots,
    output wire [5:0] O_active_slots,
    output wire [5:0] O_retire_slots,
    input wire [63:0] I_tokens,
    output wire [63:0] O_pending_tokens,
    output wire [63:0] O_active_tokens,
    output wire [63:0] O_retire_tokens,
    input wire [63:0] I_generations,
    output wire [63:0] O_pending_generations,
    output wire [63:0] O_active_generations,
    output wire [63:0] O_retire_generations,
    input wire [1:0] I_resident,
    output wire [1:0] O_pending_resident,
    output wire [1:0] O_active_resident,
    output wire [1:0] O_retire_resident,
    input wire [2:0] I_effect,
    output wire [2:0] O_pending_effect,
    output wire [2:0] O_active_effect,
    output wire [2:0] O_retire_effect,
    input wire [15:0] I_duration_frames,
    output wire [15:0] O_pending_duration_frames,
    output wire [15:0] O_active_duration_frames,
    output wire [15:0] O_retire_duration_frames,
    input wire [16:0] I_progress,
    output wire [16:0] O_pending_progress,
    output wire [16:0] O_active_progress,
    output wire [16:0] O_retire_progress,
    input wire [3:0] I_brightness,
    output wire [3:0] O_pending_brightness,
    output wire [3:0] O_active_brightness,
    output wire [3:0] O_retire_brightness,
    input wire [3:0] I_contrast,
    output wire [3:0] O_pending_contrast,
    output wire [3:0] O_active_contrast,
    output wire [3:0] O_retire_contrast,
    input wire [4:0] I_saturation,
    output wire [4:0] O_pending_saturation,
    output wire [4:0] O_active_saturation,
    output wire [4:0] O_retire_saturation,
    input wire [2:0] I_layout,
    output wire [2:0] O_pending_layout,
    output wire [2:0] O_active_layout,
    output wire [2:0] O_retire_layout,
    input wire [1:0] I_rotation,
    output wire [1:0] O_pending_rotation,
    output wire [1:0] O_active_rotation,
    output wire [1:0] O_retire_rotation,
    input wire I_alert,
    output wire O_pending_alert,
    output wire O_active_alert,
    output wire O_retire_alert,
    input wire I_audio_required,
    output wire O_pending_audio_required,
    output wire O_active_audio_required,
    output wire O_retire_audio_required,
    input wire [17:0] I_first_y,
    output wire [17:0] O_pending_first_y,
    output wire [17:0] O_active_first_y,
    output wire [17:0] O_retire_first_y,
    input wire [1:0] I_first_bank,
    output wire [1:0] O_pending_first_bank,
    output wire [1:0] O_active_first_bank,
    output wire [1:0] O_retire_first_bank,
    input wire [31:0] I_first_tag,
    output wire [31:0] O_pending_first_tag,
    output wire [31:0] O_active_first_tag,
    output wire [31:0] O_retire_first_tag,
    input wire [1:0] I_lease_valid,
    input wire [5:0] I_lease_slots,
    input wire [63:0] I_lease_tokens,
    input wire [63:0] I_lease_generations,
    input wire [1:0] I_lease_resident,
    input wire [3:0] I_bank_valid,
    input wire [11:0] I_bank_slots,
    input wire [35:0] I_bank_rows,
    input wire [127:0] I_bank_tokens,
    input wire [127:0] I_bank_generations,
    input wire [127:0] I_bank_epochs,
    input wire [63:0] I_bank_tags,
    input wire I_audio_ready,
    input wire [31:0] I_audio_epoch
);
    wire [246:0] S_config,S_pending_config,S_active_config,S_retire_config;
    assign S_config={I_source_mask,I_from_source,I_slots,I_tokens,I_generations,I_resident,I_effect,I_duration_frames,I_progress,I_brightness,I_contrast,I_saturation,I_layout,I_rotation,I_alert,I_audio_required,I_first_y,I_first_bank,I_first_tag};
    assign {O_pending_source_mask,O_pending_from_source,O_pending_slots,O_pending_tokens,O_pending_generations,O_pending_resident,O_pending_effect,O_pending_duration_frames,O_pending_progress,O_pending_brightness,O_pending_contrast,O_pending_saturation,O_pending_layout,O_pending_rotation,O_pending_alert,O_pending_audio_required,O_pending_first_y,O_pending_first_bank,O_pending_first_tag}=S_pending_config;
    assign {O_active_source_mask,O_active_from_source,O_active_slots,O_active_tokens,O_active_generations,O_active_resident,O_active_effect,O_active_duration_frames,O_active_progress,O_active_brightness,O_active_contrast,O_active_saturation,O_active_layout,O_active_rotation,O_active_alert,O_active_audio_required,O_active_first_y,O_active_first_bank,O_active_first_tag}=S_active_config;
    assign {O_retire_source_mask,O_retire_from_source,O_retire_slots,O_retire_tokens,O_retire_generations,O_retire_resident,O_retire_effect,O_retire_duration_frames,O_retire_progress,O_retire_brightness,O_retire_contrast,O_retire_saturation,O_retire_layout,O_retire_rotation,O_retire_alert,O_retire_audio_required,O_retire_first_y,O_retire_first_bank,O_retire_first_tag}=S_retire_config;
    reg S_range_ok,S_lease_ok,S_lines_ready;
    integer S_i;
    integer S_bank_index;
    wire [3:0] S_validate_error=!S_range_ok ? 4'd1 : !S_lease_ok ? 4'd4 : 4'd0;
    wire S_allow_apply=I_allow_apply && S_lines_ready &&
        (!O_pending_audio_required || (I_audio_ready && I_audio_epoch==O_pending_epoch));
    always @* begin
        S_range_ok=I_source_mask!=0 && I_source_mask[I_from_source] && I_effect<=6 &&
            I_progress<=17'd65536 && (I_source_mask!=3 || I_duration_frames!=0) &&
            (I_brightness<=4 || I_brightness>=12) && (I_contrast<=4 || I_contrast>=12) &&
            I_saturation<=16 && I_layout<=4;
        S_lease_ok=1;
        S_lines_ready=1;
        S_bank_index=0;
        for (S_i=0;S_i<2;S_i=S_i+1) begin
            if (I_source_mask[S_i]) begin
                if (I_slots[S_i*3 +: 3]>=6 || I_tokens[S_i*32 +: 32]==0 ||
                    I_first_y[S_i*9 +: 9]>=480 || (I_resident[S_i] && I_slots[S_i*3 +: 3]!=5)) S_range_ok=0;
                if (!I_lease_valid[S_i] || I_lease_slots[S_i*3 +: 3]!=I_slots[S_i*3 +: 3] ||
                    I_lease_tokens[S_i*32 +: 32]!=I_tokens[S_i*32 +: 32] ||
                    I_lease_generations[S_i*32 +: 32]!=I_generations[S_i*32 +: 32] ||
                    I_lease_resident[S_i]!=I_resident[S_i]) S_lease_ok=0;
            end
            S_bank_index=S_i*2+O_pending_first_bank[S_i];
            if (O_pending_source_mask[S_i] && (!I_bank_valid[S_bank_index] ||
                I_bank_slots[S_bank_index*3 +: 3]!=O_pending_slots[S_i*3 +: 3] ||
                I_bank_rows[S_bank_index*9 +: 9]!=O_pending_first_y[S_i*9 +: 9] ||
                I_bank_tokens[S_bank_index*32 +: 32]!=O_pending_tokens[S_i*32 +: 32] ||
                I_bank_generations[S_bank_index*32 +: 32]!=O_pending_generations[S_i*32 +: 32] ||
                I_bank_epochs[S_bank_index*32 +: 32]!=O_pending_epoch ||
                I_bank_tags[S_bank_index*16 +: 16]!=O_pending_first_tag[S_i*16 +: 16])) S_lines_ready=0;
        end
    end
    frame_commit_cdc #(.CONFIG_BITS(247),.QUEUE_BITS(QUEUE_BITS),.EPOCH_BITS(EPOCH_BITS)) u_commit (
        .I_host_clk(I_host_clk),
        .I_video_clk(I_video_clk),
        .I_async_reset(I_async_reset),
        .I_submit_valid(I_submit_valid),
        .O_submit_ready(O_submit_ready),
        .I_config(S_config),
        .I_tag(I_tag),
        .I_validate_error(S_validate_error),
        .I_abort(I_abort),
        .O_next_epoch(O_next_epoch),
        .O_busy(O_busy),
        .O_done_valid(O_done_valid),
        .I_done_ready(I_done_ready),
        .O_error(O_error),
        .O_prepare_error(O_prepare_error),
        .O_retire_error(O_retire_error),
        .O_tag(O_tag),
        .O_epoch(O_epoch),
        .O_previous_epoch(O_previous_epoch),
        .O_applied(O_applied),
        .O_retired(O_retired),
        .O_quarantined(O_quarantined),
        .O_host_response_discarded(O_host_response_discarded),
        .O_pending_valid(O_pending_valid),
        .O_pending_config(S_pending_config),
        .O_pending_tag(O_pending_tag),
        .O_pending_epoch(O_pending_epoch),
        .O_prepare_valid(O_prepare_valid),
        .I_prepare_ready(I_prepare_ready),
        .O_prepare_abort(O_prepare_abort),
        .I_prepare_done_valid(I_prepare_done_valid),
        .O_prepare_done_ready(O_prepare_done_ready),
        .I_prepare_done_tag(I_prepare_done_tag),
        .I_prepare_done_epoch(I_prepare_done_epoch),
        .I_prepare_done_error(I_prepare_done_error),
        .I_frame_start(I_frame_start),
        .I_allow_apply(S_allow_apply),
        .I_video_abort(I_video_abort),
        .O_active_valid(O_active_valid),
        .O_active_config(S_active_config),
        .O_active_tag(O_active_tag),
