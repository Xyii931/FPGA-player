            if (!S_line_valid[S_selected] || I_line_ready) begin
                S_selection_valid<=0; S_prefer_b<=!S_selected;
            end
        end else if (|S_line_valid) begin
            S_selected<=S_line_valid[S_prefer_b] ? S_prefer_b : !S_prefer_b;
            S_selection_valid<=1;
        end
