        .O_bank_valid(O_bank_valid[0 +: 2]),
        .O_bank_reserved(O_bank_reserved[0 +: 2]),
        .O_bank_slots(O_bank_slots[0 +: 6]),
        .O_bank_rows(O_bank_rows[0 +: 18]),
        .O_bank_tokens(O_bank_tokens[0 +: 64]),
        .O_bank_generations(O_bank_generations[0 +: 64]),
        .O_bank_epochs(O_bank_epochs[0 +: 64]),
        .O_bank_tags(O_bank_tags[0 +: 32]),
        .I_retire_request(I_retire_request[0 +: 1]),
        .O_retire_ack(O_retire_ack[0 +: 1]),
        .O_host_retired(O_host_retired[0 +: 1]),
        .O_host_busy(O_host_busy[0 +: 1]),
        .O_host_tag_exhausted(O_host_tag_exhausted[0 +: 1]),
        .O_release_discarded(O_release_discarded[0 +: 1]),
        .O_event_discarded(O_event_discarded[0 +: 1]),
        .O_response_discarded(O_response_discarded[0 +: 1]),
        .O_mem_valid(O_mem_valid[0 +: 1]),
        .I_mem_ready(I_mem_ready[0 +: 1]),
        .O_mem_addr(O_mem_addr[0 +: 21]),
        .O_mem_tag(O_mem_tag[0 +: 32]),
