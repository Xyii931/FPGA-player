        .I_read_valid(I_read_valid[0 +: 1]),
        .O_read_ready(O_read_ready[0 +: 1]),
        .I_read_bank(I_read_bank[0 +: 1]),
        .I_read_x(I_read_x[0 +: 10]),
        .O_pixel_valid(O_pixel_valid[0 +: 1]),
        .O_rgba(O_rgba[0 +: 32]),
        .O_pixel_bank(O_pixel_bank[0 +: 1]),
        .O_pixel_x(O_pixel_x[0 +: 10]),
        .O_pixel_token(O_pixel_token[0 +: 32]),
        .O_pixel_generation(O_pixel_generation[0 +: 32]),
        .O_pixel_epoch(O_pixel_epoch[0 +: 32]),
